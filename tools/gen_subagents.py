#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""按角色模板生成 .opencode/agents/*.md —— 让「提示词里的路径」与「权限里的路径」逐字一致。

为什么需要生成：
  OpenCode 的 permission 是按**路径**静态生效的，而流水线要求「一篇文献一个 worker，
  只能读自己那篇 txt、只能写自己那条笔记」。手写二十多份必然出现漂移（旧版本就出现过
  提示词写 _probe/notes/、权限写 _probe/full/ 的矛盾）。所以角色正文只维护一份
  （litrev/_probe/AGENT_ROLES.md），路径由本脚本注入。

用法：
  python tools/gen_subagents.py            # 生成/更新
  python tools/gen_subagents.py --check    # 只检查是否与模板一致（不一致退出 1）
  python tools/gen_subagents.py --dry-run  # 打印将要写入的文件清单
"""

import argparse
import json
import re
import sys
from pathlib import Path

# Windows PowerShell 默认 GBK 控制台会让 print("✓ ...") 抛 UnicodeEncodeError，
# 而且崩在「比对已经成功之后」，容易被误读成 agent 定义不同步。统一切成 UTF-8。
try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except (AttributeError, ValueError, OSError):
    pass

ROOT = Path(__file__).resolve().parent.parent
ROLES_FILE = ROOT / "litrev/_probe/AGENT_ROLES.md"
TEXTS_DIR = ROOT / "litrev/_probe/texts"
NOTES_DIR = ROOT / "litrev/_probe/notes"
FULL_DIR = ROOT / "litrev/_probe/full"
ALIAS_FILE = ROOT / "litrev/aliases.json"
BATCH_FILE = ROOT / "litrev/_probe/audit/BATCHES.json"
AGENTS_DIR = ROOT / ".opencode/agents"
MAP_FILE = ROOT / "litrev/_probe/AGENT_MAP.md"
MANIFEST = ROOT / "litrev/_probe/.generated_agents.json"

CONTRACT = "litrev/_probe/CONTRACT.md"
CONTRACT_AUDIT = "litrev/_probe/AUDIT_CONTRACT.md"

YEAR_RE = re.compile(r"(19|20)\d{2}")

GENERATED_HEAD = ("<!-- AUTO-GENERATED by tools/gen_subagents.py "
                  "from litrev/_probe/AGENT_ROLES.md：不要手改，改模板后重新生成 -->")

ROLE_RE = re.compile(r"^## ROLE: (\S+)\s*$(.*?)(?=^## ROLE: |\Z)", re.M | re.S)


def txt_health(text):
    """词/行 < 3 说明文字层坏到无法按行取句，不值得为它生成抽取工。"""
    lines = [l for l in text.splitlines() if l.strip() and not l.startswith("#")
             and not l.startswith("<<<PAGE")]
    if not lines:
        return 0.0
    return round(sum(len(l.split()) for l in lines) / len(lines), 2)


def load_manifest():
    path = ROOT / "litrev/_index/manifest.csv"
    if not path.exists():
        return {}
    import csv
    with open(path, encoding="utf-8-sig", newline="") as fh:
        return {r["file"]: r for r in csv.DictReader(fh)}


def load_aliases():
    if not ALIAS_FILE.exists():
        return {}
    return json.loads(ALIAS_FILE.read_text(encoding="utf-8"))


def cite_of(source, stem, aliases):
    """算出这张卡片里该写的「作者, 年份」。

    作者不能交给模型去猜：`Survey2025_...` 的文件名里没有姓氏，卡片却写 `Ling et al.`；
    `SharmaThesis_...` 连年份都没有。而 `verify` 会拿这两个值和文件名比，猜错就判 AUTHOR、
    整篇 verify 变红。所以由生成器一次算定、写进提示词，模型只负责照抄。
    """
    m = YEAR_RE.search(stem)
    year = m.group(0) if m else ""
    head = stem[:m.start()] if m else stem
    raw = re.sub(r"[^A-Za-z]", "", head)
    names = aliases.get(source) or []
    return (names[0] if names else raw) or "", year


def load_roles():
    if not ROLES_FILE.exists():
        sys.exit(f"[!] 缺少角色模板：{ROLES_FILE}")
    text = ROLES_FILE.read_text(encoding="utf-8")
    roles = {m.group(1): m.group(2).strip() for m in ROLE_RE.finditer(text)}
    if not roles:
        sys.exit("[!] AGENT_ROLES.md 里没有 `## ROLE: xxx` 段落")
    return roles


def slugify(stem):
    s = re.sub(r"[^a-z0-9]+", "-", stem.lower()).strip("-")
    return re.sub(r"-{2,}", "-", s)


def fill(tpl, **kw):
    out = tpl
    for k, v in kw.items():
        out = out.replace("{{%s}}" % k, v)
    left = re.findall(r"\{\{[A-Z_]+\}\}", out)
    if left:
        sys.exit(f"[!] 角色模板里残留未替换的占位符：{sorted(set(left))}")
    return out


def perm_block(lines):
    """把 permission 字典写成 YAML 块（保持键出现顺序：通配在前，具体在后）。"""
    out = ["permission:"]
    for key, rules in lines:
        if isinstance(rules, str):
            out.append(f"  {key}: {rules}")
            continue
        out.append(f"  {key}:")
        for pat, act in rules:
            out.append(f'    "{pat}": {act}')
    return "\n".join(out)


def agent_md(description, body, perms):
    # 注意：frontmatter 必须在文件第一字节，所以生成标记放在正文首行
    return (f"---\n"
            f"description: {description}\n"
            f"mode: subagent\n"
            f"{perm_block(perms)}\n---\n\n"
            f"{GENERATED_HEAD}\n\n{body}\n")


READ_ONLY = [
    ("bash", [("*", "deny")]),
    ("grep", [("*", "deny")]),
    ("glob", [("*", "deny")]),
    ("webfetch", "deny"),
    ("websearch", "deny"),
]


def build(roles):
    """返回 {相对路径: 文件内容} 与映射表行。"""
    files, rows, done = {}, [], []

    if not TEXTS_DIR.exists():
        sys.exit(f"[!] 缺少正文目录：{TEXTS_DIR}（先跑 python litrev/litrev.py text）")
    txts = sorted(TEXTS_DIR.glob("*.txt"))
    if not txts:
        sys.exit("[!] texts/ 下没有 txt")

    man = load_manifest()
    aliases = load_aliases()
    skipped = []
    seen = {}
    for path in txts:
        stem = path.stem
        text = path.read_text(encoding="utf-8", errors="replace")
        src = ""
        for line in text.splitlines()[:3]:
            if line.startswith("# SOURCE:"):
                src = line.split(":", 1)[1].strip()
                break
        rec = man.get(src, {})
        if rec.get("duplicate_of"):
            skipped.append((stem, f"内容与 {rec['duplicate_of']} 重复"))
            continue
        wpl = txt_health(text)
        if wpl < 3:
            skipped.append((stem, f"文字层不可用（{wpl} 词/行），需 OCR 或视觉抄录"))
            continue

        slug = slugify(stem)
        if slug in seen:
            sys.exit(f"[!] 文件名主干归一后撞名：{stem} 与 {seen[slug]}，先改名")
        seen[slug] = stem

        txt = f"litrev/_probe/texts/{stem}.txt"
        # 卡片落点：新卡片一律进 full/。裁判（litrev.py）的 CARD_DIR 只读 full/ 的 7 节卡片，
        # 落到 notes/ 的条目式卡片永远进不了判定表（round-13 实测：抽取通了，链路仍是断的）。
        # notes/ 下已有的 3 篇早期基线不迁移、也不另建副本——原地返工，路径仍指 notes/。
        full = f"litrev/_probe/full/{stem}.md"
        legacy = f"litrev/_probe/notes/{stem}.md"
        if (ROOT / full).exists():
            target = full
        elif (ROOT / legacy).exists():
            target = legacy
        else:
            target = full

        if (ROOT / target).exists():
            # 卡片已存在 = 首次抽取已完成。不生成 ex-：它只有创建权限，派它只会撞到已有文件。
            done.append((stem, target))
            ex = None
        else:
            author, year = cite_of(src, stem, aliases)
            if not (author and year):
                skipped.append((stem, f"取不到作者/年份（作者={author or '空'}、年份={year or '空'}）："
                                      f"无法生成引文标注，先把文件名改成 AuthorYYYY_xxx，"
                                      f"或在 litrev/aliases.json 里登记 {stem}.pdf"))
                continue
            ex = f"ex-{slug}"
            files[f".opencode/agents/{ex}.md"] = agent_md(
                f"{stem} 的抽取工。只读一篇 txt、只创建一张 7 节卡片；逐字抄引文并标 PDF 物理页，"
                f"某节原文没有就写未涉及。",
                fill(roles["extractor"], DOC=stem, TXT=txt, CARD=target, CONTRACT=CONTRACT,
                     CITE=author, YEAR=year),
                [("read", [("*", "deny"), (CONTRACT, "allow"), (txt, "allow")]),
                 ("edit", [("*", "deny"), (target, "allow")])] + READ_ONLY,
            )
        files[f".opencode/agents/qx-{slug}.md"] = agent_md(
            f"{stem} 的返工手。只改这一条笔记/卡片的引文范围（扩句），其余一字不动。",
            fill(roles["quote-expander"], DOC=stem, TXT=txt, NOTE=target, CONTRACT=CONTRACT),
            [("read", [("*", "deny"), (CONTRACT, "allow"), (txt, "allow"), (target, "allow")]),
             ("edit", [("*", "deny"), (target, "allow")])] + READ_ONLY,
        )
        rows.append({"doc": stem, "ex": ex, "qx": f"qx-{slug}"})

    batches = []
    if BATCH_FILE.exists():
        batches = json.loads(BATCH_FILE.read_text(encoding="utf-8")).get("batches", [])

    batch_rows = []
    for b in batches:
        bid, inp, outp = b["id"], b["input"], b["output"]
        files[f".opencode/agents/auditor-{slugify(bid)}.md"] = agent_md(
            f"审计员 {bid}。闭卷判「引文是否撑得起论断」，只读本批次输入，只写本批次输出。",
            fill(roles["auditor"], BATCH_IN=inp, BATCH_OUT=outp, CONTRACT_AUDIT=CONTRACT_AUDIT),
            [("read", [("*", "deny"), (CONTRACT_AUDIT, "allow"), (inp, "allow"), (outp, "allow")]),
             ("edit", [("*", "deny"), (outp, "allow")])] + READ_ONLY,
        )
        batch_rows.append({"id": bid, "agent": f"auditor-{slugify(bid)}",
                           "input": inp, "output": outp, "note": b.get("note", "")})

    if "checker" in roles:
        files[".opencode/agents/checker.md"] = agent_md(
            "核验员。独立运行 litrev.py verify/matrix/locate/audit-count/audit-stale，把判定码翻译成可执行的待改清单。只读只跑，不改任何稿件。",
            roles["checker"],
            [("read", [("*", "allow")]),
             ("edit", [("*", "deny")]),
             ("bash", [("*", "deny"),
                       ("python litrev/litrev.py verify*", "allow"),
                       ("python litrev/litrev.py matrix*", "allow"),
                       ("python litrev/litrev.py locate*", "allow"),
                       ("python litrev/litrev.py audit-count*", "allow"),
                       ("python litrev/litrev.py audit-stale*", "allow")]),
             ("grep", [("*", "allow")]),
             ("glob", [("*", "allow")]),
             ("webfetch", "deny"),
             ("websearch", "deny")],
        )

    return files, rows, batch_rows, skipped, done


def map_markdown(rows, batch_rows):
    lines = ["# 子代理映射表", "",
             "> 由 `tools/gen_subagents.py` 生成，与 `.opencode/agents/` 同源。"
             "主控派活前先查这张表，不要凭记忆写 agent 名。", "",
             "## 文献级（文件级隔离：每个 agent 只能读自己那篇 txt、只能写自己那条笔记）", "",
             "| 文献 | 首次抽取 | 返工扩句 |", "|---|---|---|"]
    for r in rows:
        ex = f"`{r['ex']}`" if r["ex"] else "—（卡片已存在）"
        lines.append(f"| `{r['doc']}` | {ex} | `{r['qx']}` |")
    lines += ["", "## 审计批次（批次级隔离：只能读本批输入、只能写本批输出）", "",
              "| 批次 | Agent | 输入 | 输出 | 说明 |", "|---|---|---|---|---|"]
    for b in batch_rows:
        lines.append(f"| `{b['id']}` | `{b['agent']}` | `{b['input']}` | "
                     f"`{b['output']}` | {b['note']} |")
    lines += ["", "## 固定角色", "",
              "| Agent | 职责 |", "|---|---|",
              "| `orchestrator` | 主控（primary，手写，不生成） |",
              "| `checker` | 核验（bash 白名单只放行 verify/matrix/locate/audit-count） |", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验是否与模板一致")
    ap.add_argument("--dry-run", action="store_true", help="只打印，不写盘")
    args = ap.parse_args()

    roles = load_roles()
    files, rows, batch_rows, skipped, done = build(roles)
    files["litrev/_probe/AGENT_MAP.md"] = map_markdown(rows, batch_rows)

    old = json.loads(MANIFEST.read_text(encoding="utf-8")) if MANIFEST.exists() else []
    stale = [p for p in old if p not in files]

    if args.check:
        bad = []
        for rel, content in files.items():
            f = ROOT / rel
            if not f.exists():
                bad.append(f"缺失 {rel}")
            elif f.read_text(encoding="utf-8") != content:
                bad.append(f"与模板不一致 {rel}")
        for rel in stale:
            bad.append(f"陈旧残留 {rel}")
        if bad:
            print("✗ 子代理定义与模板不同步：")
            for b in bad:
                print("  -", b)
            print("\n修：python tools/gen_subagents.py（改过 AGENT_ROLES.md 是正常流程）")
            return 1
        print(f"✓ 同步：{len(files)} 个文件与 AGENT_ROLES.md 一致")
        return 0

    if args.dry_run:
        for rel in files:
            print("would write", rel)
        for rel in stale:
            print("would remove", rel)
        return 0

    AGENTS_DIR.mkdir(parents=True, exist_ok=True)
    for rel, content in files.items():
        f = ROOT / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(content, encoding="utf-8")
    for rel in stale:
        (ROOT / rel).unlink(missing_ok=True)
    MANIFEST.write_text(json.dumps(sorted(files), ensure_ascii=False, indent=1), encoding="utf-8")

    n_ex = sum(1 for r in rows if r["ex"])
    print(f"生成 {len(files)} 个文件（{n_ex} 个抽取工 + {len(rows)} 个返工手 + "
          f"{len(batch_rows)} 个审计批次 + checker + 映射表）")
    if done:
        print("\n已有卡片、不生成抽取工（首次抽取已完成，派 ex- 只会撞到已有文件）：")
        for stem, target in done:
            print(f"  - {stem} → {target}")
    if skipped:
        print("\n未生成（这些文献不该派抽取工）：")
        for stem, why in skipped:
            print(f"  - {stem}：{why}")
    if stale:
        print("清理陈旧定义：" + "、".join(stale))
    print(f"映射表：{MAP_FILE.relative_to(ROOT)}")
    print(f"校验：python tools/gen_subagents.py --check")
    return 0


if __name__ == "__main__":
    sys.exit(main())
